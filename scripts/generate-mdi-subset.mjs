import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceRoot = path.join(projectRoot, 'src');
const mdiCssPath = path.join(projectRoot, 'node_modules', '@mdi', 'font', 'css', 'materialdesignicons.css');
const mdiFontPath = path.join(projectRoot, 'node_modules', '@mdi', 'font', 'fonts', 'materialdesignicons-webfont.woff2');
const vuetifyMdiPath = path.join(projectRoot, 'node_modules', 'vuetify', 'lib', 'iconsets', 'mdi.js');
const outputPath = path.join(sourceRoot, 'styles', 'mdi-subset.css');
const outputFontPath = path.join(sourceRoot, 'assets', 'materialdesignicons-subset.woff2');
const sourceExtensions = new Set(['.css', '.js', '.scss', '.vue']);

async function collectSourceFiles(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map(async (entry) => {
    const absolutePath = path.join(directory, entry.name);
    if (entry.isDirectory()) return collectSourceFiles(absolutePath);
    if (absolutePath === outputPath) return [];
    return sourceExtensions.has(path.extname(entry.name)) ? [absolutePath] : [];
  }));
  return nested.flat();
}

const [mdiCss, vuetifyMdi, sourceFiles] = await Promise.all([
  fs.readFile(mdiCssPath, 'utf8'),
  fs.readFile(vuetifyMdiPath, 'utf8'),
  collectSourceFiles(sourceRoot),
]);

const iconNames = new Set();
for (const sourceFile of sourceFiles) {
  const source = await fs.readFile(sourceFile, 'utf8');
  for (const match of source.matchAll(/\bmdi-[a-z0-9-]+\b/g)) iconNames.add(match[0]);
}
// Vuetify emits these aliases at runtime (checkboxes, radios, selects, etc.),
// so they cannot be discovered from the application templates alone.
for (const match of vuetifyMdi.matchAll(/\bmdi-[a-z0-9-]+\b/g)) iconNames.add(match[0]);
// The generated stylesheet's own filename is not an icon reference.
iconNames.delete('mdi-subset');

const glyphs = [];
const rules = [...iconNames].sort().map((iconName) => {
  const escapedName = iconName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const rule = mdiCss.match(new RegExp(`\\.${escapedName}::before\\s*\\{\\s*content:\\s*"([^"]+)";\\s*\\}`));
  if (!rule) throw new Error(`Could not find ${iconName} in ${mdiCssPath}`);
  glyphs.push(String.fromCodePoint(Number.parseInt(rule[1].replace('\\', ''), 16)));
  return `.${iconName}::before { content: "${rule[1]}"; }`;
});

const sourceFont = await fs.readFile(mdiFontPath);
const subset = await subsetFont(sourceFont, glyphs.join(''), { targetFormat: 'woff2' });
await fs.mkdir(path.dirname(outputFontPath), { recursive: true });
await fs.writeFile(outputFontPath, subset);

const output = `/* Generated by scripts/generate-mdi-subset.mjs. Do not edit manually. */
@font-face {
  font-family: "Material Design Icons";
  src: url("../assets/materialdesignicons-subset.woff2") format("woff2");
  font-weight: normal;
  font-style: normal;
  font-display: block;
}

.mdi::before,
.mdi-set {
  display: inline-block;
  font: normal normal normal 24px/1 "Material Design Icons";
  font-size: inherit;
  text-rendering: auto;
  line-height: inherit;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${rules.join('\n')}
`;

await fs.writeFile(outputPath, output);
console.log(`Generated ${path.relative(projectRoot, outputPath)} and ${path.relative(projectRoot, outputFontPath)} with ${rules.length} icons (${subset.length} bytes).`);
