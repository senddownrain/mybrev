#!/usr/bin/env node
/** Only approved sparse text edits; never exports a Firestore snapshot. */
import fs from 'node:fs';
import zlib from 'node:zlib';
import { selectDaysTemplates } from './prepare-days-templates.mjs';
import { editorialHash } from './lib/editorial-responsories.mjs';

const root = 'docs/audits/liturgical-common-texts-2026-11/v4';
const source = fs.readFileSync(`${root}/full-content-plan.json.gz`);
const plan = selectDaysTemplates(JSON.parse(zlib.gunzipSync(source)), JSON.parse(fs.readFileSync(`${root}/PUBLICATION_RESULT.json`)));
const out = 'src/data/liturgical/web-corrections';
const parts = [{}];
const documents = {};
for (const doc of plan.documents) {
  const fields = doc.fields.map((field) => {
    const { before, after, path, beforeSha256 } = field;
    if (typeof before !== 'string' || typeof after !== 'string'
      || path.some((key) => ['__proto__', 'constructor', 'prototype'].includes(key))) throw Error('Unsafe text edit');
    let start = 0, suffix = 0;
    while (start < before.length && start < after.length && before[start] === after[start]) start++;
    while (suffix < before.length - start && suffix < after.length - start
      && before.at(-1 - suffix) === after.at(-1 - suffix)) suffix++;
    // UTF-16 offsets, matching JavaScript slice exactly; full-field SHA is the guard.
    return [path, beforeSha256, start, before.length - start - suffix, after.slice(start, after.length - suffix)];
  });
  if (Buffer.byteLength(JSON.stringify(parts.at(-1))) + Buffer.byteLength(JSON.stringify(fields)) > 900_000) parts.push({});
  documents[doc.document] = parts.length - 1;
  parts.at(-1)[doc.document] = fields;
}
fs.mkdirSync(out, { recursive: true });
for (const name of fs.readdirSync(out)) if (/^part-\d+\.(?:json|js)$/u.test(name)) fs.unlinkSync(`${out}/${name}`);
parts.forEach((part, i) => fs.writeFileSync(`${out}/part-${i}.js`, 'export default ' + JSON.stringify(part) + ';\n'));
const metadata = { version: '2026-11-16-pr255-web-only-v1', fields: 7791, documents: 749, sourceSha256: editorialHash(source) };
fs.writeFileSync(`${out}/index.js`, `// Generated by scripts/liturgy/build-web-corrections.mjs. No base documents.\nexport const WEB_CORRECTIONS = ${JSON.stringify(metadata)};\nconst documents = ${JSON.stringify(documents)};\nconst parts = [\n${parts.map((_, i) => `  () => import('./part-${i}.js'),`).join('\n')}\n];\nexport async function webCorrectionsFor(document) {\n  const part = documents[document];\n  return part === undefined ? [] : (await parts[part]()).default[document];\n}\n`);
console.log(JSON.stringify({ ...metadata, parts: parts.length }));
